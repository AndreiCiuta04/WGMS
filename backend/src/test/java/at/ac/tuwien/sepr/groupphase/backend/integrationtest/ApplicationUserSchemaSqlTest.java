package at.ac.tuwien.sepr.groupphase.backend.integrationtest;

import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

public class ApplicationUserSchemaSqlTest {

    @Test
    public void givenLegacyApplicationUserTable_whenSchemaSqlRuns_thenAddsCurrentUserColumns() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:h2:mem:legacy-user-schema;DB_CLOSE_DELAY=-1", "sa", "")) {
            try (Statement statement = connection.createStatement()) {
                statement.execute("""
                    create table application_user (
                        id bigint generated by default as identity primary key,
                        email varchar(255) not null unique,
                        password varchar(255) not null,
                        first_name varchar(255) not null,
                        last_name varchar(255) not null,
                        admin boolean not null
                    )
                    """);
                statement.execute("""
                    insert into application_user (email, password, first_name, last_name, admin)
                    values ('legacy@example.com', 'hashed-password', 'Legacy', 'User', false)
                    """);
            }

            ScriptUtils.executeSqlScript(connection, new ClassPathResource("schema.sql"));

            assertColumnExists(connection, "failed_login_attempts");
            assertColumnExists(connection, "account_locked_until");
            assertColumnExists(connection, "anonymized");
            assertColumnExists(connection, "terms_accepted_at");
            assertColumnExists(connection, "terms_version");
            assertColumnExists(connection, "privacy_acknowledged_at");
            assertColumnExists(connection, "privacy_version");

            try (Statement statement = connection.createStatement();
                 ResultSet result = statement.executeQuery("""
                     select failed_login_attempts, account_locked_until, anonymized,
                            terms_accepted_at, terms_version, privacy_acknowledged_at, privacy_version
                     from application_user
                     where email = 'legacy@example.com'
                     """)) {
                assertTrue(result.next());
                assertEquals(0, result.getInt("failed_login_attempts"));
                assertNull(result.getTimestamp("account_locked_until"));
                assertFalse(result.getBoolean("anonymized"));
                assertNull(result.getTimestamp("terms_accepted_at"));
                assertNull(result.getString("terms_version"));
                assertNull(result.getTimestamp("privacy_acknowledged_at"));
                assertNull(result.getString("privacy_version"));
            }
        }
    }

    private void assertColumnExists(Connection connection, String columnName) throws Exception {
        try (ResultSet columns = connection.getMetaData().getColumns(null, null, "APPLICATION_USER", columnName.toUpperCase())) {
            assertTrue(columns.next(), "Expected application_user." + columnName + " to exist");
        }
    }
}
